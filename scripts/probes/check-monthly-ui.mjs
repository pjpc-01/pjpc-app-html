import { SITE } from './_auth.mjs'
import { chromium } from 'playwright'
const b = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
const c = await b.newContext({ viewport: { width: 1400, height: 1100 }, locale: 'zh-CN' })
const p = await c.newPage()
const errs = [], bad = []
p.on('pageerror', e => errs.push(String(e).slice(0, 100)))
p.on('response', r => { if (r.url().includes('/api/') && r.status() >= 400) bad.push(r.status() + ' ' + r.url().split('?')[0].replace(SITE, '')) })
await p.goto(SITE + '/login', { waitUntil: 'networkidle' }).catch(() => {})
await p.waitForTimeout(1600)
await p.fill('#login-email', 'admin@pjpc.com')
await p.fill('#login-password', '1234567890')
await p.locator('button:has-text("安全登录")').first().click()
await p.waitForTimeout(8000)
await p.goto(SITE + '/monthly-tests', { waitUntil: 'networkidle' })
await p.waitForTimeout(2500)
// 选年级 Form 1
await p.locator('select').nth(2).selectOption({ label: '中一' }).catch(async () => {
  await p.locator('select').nth(2).selectOption('Form 1')
})
await p.waitForTimeout(3000)
const inputs = await p.locator('table input').count()
const heads = await p.locator('table thead th').allInnerTexts()
const rows = await p.locator('table tbody tr').count()
console.log('科目列:', heads.join(' | '))
console.log('学生行:', rows, '| 输入格:', inputs)
const t = await p.evaluate(() => document.body.innerText.replace(/\s+/g, ' '))
const i = t.indexOf('已录')
console.log('进度:', i >= 0 ? t.slice(i, i + 20) : '(无)')
console.log('失败请求:', [...new Set(bad)].slice(0, 4), '| JS 错:', errs.slice(0, 2))
await b.close()
