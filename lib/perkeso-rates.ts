// Lookup functions
export function getSocsoEmployee(salary: number): number {
  const band = SOCSO_BANDS.find(b => salary <= b.max)
  return band ? band.employee : 29.75
}

export function getSocsoEmployer(salary: number): number {
  const band = SOCSO_BANDS.find(b => salary <= b.max)
  return band ? band.employer : 104.15
}

export function getEisContribution(salary: number): number {
  const band = EIS_BANDS.find(b => salary <= b.max)
  return band ? band.amount : 11.90
}
